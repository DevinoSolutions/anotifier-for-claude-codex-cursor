// tests/approval-setup.test.mjs — `anotifier approval setup` end to end, as a
// subprocess against a fake ntfy server and a throwaway HOME. Covers the
// lockdown check that runs before the setup round trip (review of PR #96, M3)
// and TLS verification in the setup path (M1).
import { describe, it, before, after, beforeEach } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';
import {
  startFakeNtfy, actionByLabel, tap, selfSignedPems, repoRoot,
} from './approval-helpers.mjs';

const TOKEN = 'tk_setuptestabcdefghijklmnopqrs';
let fake;
const homes = [];
before(async () => { fake = await startFakeNtfy(); });
after(async () => {
  await fake.close();
  for (const h of homes) fs.rmSync(h, { recursive: true, force: true });
});
beforeEach(() => fake.reset());

function freshHome() {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'aan-appr-setup-'));
  fs.mkdirSync(path.join(home, '.claude'));
  homes.push(home);
  return home;
}

// Non-interactive setup: no TTY, so no prompts; the token comes from the env.
function runSetup({ home, server, env = {}, timeoutMs = 60000 }) {
  return new Promise((resolve) => {
    const childEnv = {
      ...process.env, HOME: home, USERPROFILE: home, NO_COLOR: '1', ANOTIFIER_TELEMETRY: '0',
      ANOTIFIER_EXPERIMENTAL_APPROVAL: '1', AAN_APPROVAL_TOKEN: TOKEN, ...env,
    };
    const child = spawn(process.execPath, ['cli/index.mjs', 'approval', 'setup', '--server', server], {
      cwd: repoRoot, env: childEnv, stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true,
    });
    let stdout = '';
    let stderr = '';
    child.stdout.setEncoding('utf8');
    child.stderr.setEncoding('utf8');
    child.stdout.on('data', (c) => { stdout += c; });
    child.stderr.on('data', (c) => { stderr += c; });
    const killer = setTimeout(() => child.kill('SIGKILL'), timeoutMs);
    child.on('close', (status) => { clearTimeout(killer); resolve({ status, stdout, stderr }); });
  });
}

const readApproval = (home) => JSON.parse(fs.readFileSync(path.join(home, '.anotifier', 'approval.json'), 'utf8'));
const hookInstalled = (home) => {
  try { return JSON.stringify(JSON.parse(fs.readFileSync(path.join(home, '.claude', 'settings.json'), 'utf8'))).includes('approve.mjs'); } catch { return false; }
};

describe('approval setup checks the server is locked down first', () => {
  it('an open server is refused: no round trip, not enabled, no hook, the recipe is pointed to', async () => {
    const home = freshHome();
    const res = await runSetup({ home, server: fake.base });
    const text = res.stdout + res.stderr;
    assert.equal(res.status, 1, text);
    assert.match(text, /not locked down/);
    assert.match(text, /anonymous read of the request topic got HTTP 200/);
    assert.match(text, /docs\/design\/remote-approval\.md, section 2\.5/);
    assert.match(text, /Remote approval stays off/);
    assert.equal(readApproval(home).enabled, false);
    assert.equal(hookInstalled(home), false);
    assert.equal(fake.subscribes.length, 0, 'no subscribe: the round trip never started');
    assert.equal(fake.published.length, 0);
    assert.equal(fake.posts.length, 0, 'the first probe already failed, so nothing was posted');
    assert.ok(fake.requests.every((q) => q.auth === null), 'the probe sent no credentials');
  });

  it('a server with open publish is refused, naming fake prompts', async () => {
    const home = freshHome();
    // The names are generated by setup, so accept any prefix: reads are denied
    // for every client without credentials, publishes are not.
    fake.mode.denyAnonymous = { responsePrefix: 'ans-never-matches', openPublish: true };
    const res = await runSetup({ home, server: fake.base });
    const text = res.stdout + res.stderr;
    assert.equal(res.status, 1, text);
    assert.match(text, /anonymous publish to the request topic got HTTP 200/);
    assert.match(text, /fake approval prompts/);
    assert.equal(readApproval(home).enabled, false);
    assert.equal(fake.subscribes.length, 0);
  });

  it('a locked-down server passes the check and the round trip enables it', async () => {
    const home = freshHome();
    fake.mode.denyAnonymous = { responseTopicRe: /^ans-[A-Za-z0-9_-]{16}_/ };
    fake.onRequest = (payload) => tap(actionByLabel(payload, 'Approve'));
    const res = await runSetup({ home, server: fake.base });
    const text = res.stdout + res.stderr;
    assert.equal(res.status, 0, text);
    assert.match(text, /refuses anonymous reads and publishes/);
    assert.match(text, /Round trip works/);
    assert.equal(readApproval(home).enabled, true);
    assert.equal(hookInstalled(home), true);
    // The probes came first and carried no credentials; the round trip used the token.
    const firstAuthed = fake.requests.findIndex((q) => q.auth !== null);
    assert.ok(firstAuthed >= 3, `three anonymous probes before the first authenticated request (got ${firstAuthed})`);
    assert.ok(fake.requests.slice(0, 3).every((q) => q.auth === null));
    assert.equal(fake.subscribes[0].auth, `Bearer ${TOKEN}`);
  });
});

describe('approval setup warns when the ntfy account has no tier', () => {
  const lockedDown = () => {
    fake.mode.denyAnonymous = { responseTopicRe: /^ans-[A-Za-z0-9_-]{16}_/ };
    fake.onRequest = (payload) => tap(actionByLabel(payload, 'Approve'));
  };

  it('a tierless account gets the warning with both commands, and setup still completes', async () => {
    const home = freshHome();
    lockedDown();
    fake.mode.account = { body: { username: 'agent', role: 'user' } };
    const res = await runSetup({ home, server: fake.base });
    const text = res.stdout + res.stderr;
    assert.equal(res.status, 0, text);
    assert.match(text, /account has no tier/);
    assert.match(text, /intermittent 403s/);
    assert.match(text, /section 2\.5, step 1/);
    assert.match(text, /ntfy tier add --name=approval approval/);
    assert.match(text, /ntfy user change-tier <user> approval/);
    assert.ok(!text.includes(TOKEN), 'the token is never printed');
    assert.match(text, /Round trip works/);
    assert.equal(readApproval(home).enabled, true);
    assert.equal(hookInstalled(home), true);
    const acct = fake.requests.findIndex((q) => q.path === '/v1/account');
    assert.ok(acct >= 3, 'after the three anonymous probes');
    assert.equal(fake.requests[acct].auth, `Bearer ${TOKEN}`);
    assert.ok(acct < fake.requests.findIndex((q) => q.path.endsWith('/json') && q.auth), 'before the round trip');
  });

  it('an account with a tier prints no warning', async () => {
    const home = freshHome();
    lockedDown();
    fake.mode.account = { body: { username: 'agent', tier: { code: 'approval', name: 'approval' } } };
    const res = await runSetup({ home, server: fake.base });
    const text = res.stdout + res.stderr;
    assert.equal(res.status, 0, text);
    assert.doesNotMatch(text, /no tier/);
    assert.equal(readApproval(home).enabled, true);
  });

  it('a failed check prints nothing extra and setup continues', async () => {
    const home = freshHome();
    lockedDown();
    fake.mode.account = { status: 401, body: {} };
    const res = await runSetup({ home, server: fake.base });
    const text = res.stdout + res.stderr;
    assert.equal(res.status, 0, text);
    assert.doesNotMatch(text, /no tier|intermittent/);
    assert.equal(readApproval(home).enabled, true);
  });
});

describe('approval setup verifies certificates (review of PR #96, M1)', () => {
  it('a self-signed server is refused even with NODE_TLS_REJECT_UNAUTHORIZED=0 in the environment', async () => {
    const secure = await startFakeNtfy({ tls: selfSignedPems() });
    try {
      const home = freshHome();
      const res = await runSetup({ home, server: secure.base, env: { NODE_TLS_REJECT_UNAUTHORIZED: '0' } });
      const text = res.stdout + res.stderr;
      assert.equal(res.status, 1, text);
      assert.match(text, /Could not check that the server is locked down/);
      assert.equal(readApproval(home).enabled, false);
      assert.equal(secure.requests.length, 0, 'the TLS handshake was refused, the server saw no request');
    } finally {
      await secure.close();
    }
  });
});
